  to_do = [start]
  visited = set()
  order = []

  while to_do:
    room = to_do.pop(0)

    if room in visited:
      continue
    visited.add(room)
    order.append(room)
    if room == goal:
      return order
    for nxt in map_rooms[room]:
      if nxt not in visited:
        to_do.append(nxt)

  return order
