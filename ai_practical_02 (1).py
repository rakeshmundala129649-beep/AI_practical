door_cost = {
    ("A","B"): 1,
    ("A","C"): 5,
    ("B","D"): 1,
    ("C","D"): 1,
    ("D","G"): 1,
}
def path_cost(path):
  total = 0
  for i in range(len(path)-1):
    door = (path[i], path[i+1]) # Corrected to use tuples and next element in path
    total = total + door_cost[door] # Corrected to add cost
  return total

path1 = ["A", "B", "D", "G"]
